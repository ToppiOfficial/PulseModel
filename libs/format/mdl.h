// Procedural bone data for STUDIO_PROC_JIGGLE, reached through
// mstudiobone_t::procindex (a byte offset relative to the owning bone).
// All angles are radians; boingImpactAngle is already a cosine.
struct mstudiojigglebone_t {
    int32_t flags;

    // general
    float length;  // distance from the bone base, along the bone, to the tip
    float tipMass;

    // flexible
    float yawStiffness;
    float yawDamping;
    float pitchStiffness;
    float pitchDamping;
    float alongStiffness;
    float alongDamping;

    // angle constraint
    float angleLimit; // max deflection of the tip

    // yaw constraint
    float minYaw;
    float maxYaw;
    float yawFriction;
    float yawBounce;

    // pitch constraint
    float minPitch;
    float maxPitch;
    float pitchFriction;
    float pitchBounce;

    // base spring
    float baseMass;
    float baseStiffness;
    float baseDamping;
    float baseMinLeft;
    float baseMaxLeft;
    float baseLeftFriction;
    float baseMinUp;
    float baseMaxUp;
    float baseUpFriction;
    float baseMinForward;
    float baseMaxForward;
    float baseForwardFriction;

    // boing
    float boingImpactSpeed;
    float boingImpactAngle;
    float boingDampingRate;
    float boingFrequency;
    float boingAmplitude;
};
static_assert(sizeof(mstudiojigglebone_t) == 140, "mstudiojigglebone_t layout");

