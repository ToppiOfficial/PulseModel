// mdl.h - PulseMDL
//
// On-disk .mdl (studio model, version 49) structures, re-declared from format
// facts (SDK-2013 / CS:GO-era studio.h studied as reference; typed fresh, not
// pasted). Field order, widths and padding are interface facts of the binary
// format - every struct size is locked by a static_assert.
//
// Conventions:
// - All "index" fields are byte offsets. Offsets in studiohdr_t are relative
//   to the file start; offsets in any other struct are relative to that
//   struct's own first byte (including studiohdr2_t's).
// - Pointer-sized slots in the original headers (IMaterial*, cache pointers)
//   are declared as int32 pairs here; they are written zeroed on disk.
// - Struct member types use the pulse::math value types (plain float PODs).

